// Writes app/asset-list.js: every file the app needs offline + a content hash for the cache name.
// Run after any change to app/ (tests/run.sh does it first).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";
const APP = new URL("../app/", import.meta.url).pathname;
const SKIP = new Set(["asset-list.js", "service-worker.js"]);
const files = [];
(function walk(d) { for (const f of readdirSync(d).sort()) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (!SKIP.has(f) && !f.startsWith(".")) files.push(relative(APP, p)); } })(APP);
const h = createHash("sha256");
for (const f of files) { h.update(f); h.update(readFileSync(join(APP, f))); }
const version = h.digest("hex").slice(0, 12);
const assets = ["./", ...files.map((f) => "./" + f)];
writeFileSync(join(APP, "asset-list.js"), `// GENERATED by tools/gen-asset-list.mjs — do not edit.\nself.CACHE_VERSION = "fl10-${version}";\nself.ASSETS = ${JSON.stringify(assets, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`asset-list.js: ${assets.length} files, cache fl10-${version}`);
